-- =====================================================================================
-- 01_criar_banco.sql  -  Star Schema: 1 fato + 4 dimensoes
-- -------------------------------------------------------------------------------------
-- Quem roda isso e o src/carregar.py (logo depois de recriar o banco do zero).
-- A logica: a FATO guarda os numeros de cada item comprado e as DIMENSOES guardam
-- o "quem", o "como" e o "onde". Elas se ligam por chaves substitutas (sk_...).
-- =====================================================================================


-- -------------------------------------------------------------------------------------
-- DIMENSOES
-- sk_... = chave substituta (numero inteiro, so do banco). A chave "de verdade" (CNPJ,
-- codigo da modalidade, sigla da UF) fica guardada tambem, com UNIQUE pra nao repetir.
-- -------------------------------------------------------------------------------------

-- QUEM COMPROU: uma linha por CNPJ de orgao (cada CNPJ e uma unidade compradora)
CREATE TABLE dim_orgao (
    sk_orgao     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj_orgao   VARCHAR(14)  NOT NULL UNIQUE,
    nome_orgao   VARCHAR(255) NOT NULL,
    poder        VARCHAR(20)  NOT NULL
        CHECK (poder IN ('Executivo', 'Legislativo', 'Judiciário', 'Não informado'))
);

-- QUEM VENDEU: uma linha por CNPJ/CPF de fornecedor (filial com CNPJ diferente = outro fornecedor)
CREATE TABLE dim_fornecedor (
    sk_fornecedor    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ni_fornecedor    VARCHAR(30)  NOT NULL UNIQUE,
    nome_fornecedor  VARCHAR(255),
    tipo_pessoa      VARCHAR(2)   CHECK (tipo_pessoa IN ('PJ', 'PF', 'PE')),
    porte            VARCHAR(20)
);

-- COMO COMPROU: uma linha por modalidade (pregao, dispensa...)
CREATE TABLE dim_modalidade (
    sk_modalidade    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modalidade_id    INTEGER      NOT NULL UNIQUE,
    nome_modalidade  VARCHAR(50)  NOT NULL
);

-- ONDE: uma linha por UF, ja com a regiao (que o arquivo nao trazia)
CREATE TABLE dim_localidade (
    sk_localidade  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uf_sigla       VARCHAR(2)   NOT NULL UNIQUE,
    uf_nome        VARCHAR(50)  NOT NULL,
    regiao         VARCHAR(20)  NOT NULL
        CHECK (regiao IN ('Norte', 'Nordeste', 'Centro-Oeste', 'Sudeste', 'Sul', 'Não informado'))
);


-- -------------------------------------------------------------------------------------
-- LINHA "NAO INFORMADO" (sk = -1)
-- Rede de seguranca: se algum item chegar sem orgao, fornecedor, modalidade ou UF, a carga
-- aponta ele pra -1 em vez de deixar a FK solta. O -1 fica fora da numeracao 1, 2, 3...
-- entao nunca bate com uma chave de verdade. Nesta base nao sobrou nenhum, mas fica pronto.
-- -------------------------------------------------------------------------------------
INSERT INTO dim_orgao      (sk_orgao, cnpj_orgao, nome_orgao, poder)
    VALUES (-1, '00000000000000', 'NÃO INFORMADO', 'Não informado');
INSERT INTO dim_fornecedor (sk_fornecedor, ni_fornecedor, nome_fornecedor, tipo_pessoa, porte)
    VALUES (-1, 'NAO INFORMADO', 'NÃO INFORMADO', NULL, NULL);
INSERT INTO dim_modalidade (sk_modalidade, modalidade_id, nome_modalidade)
    VALUES (-1, -1, 'Não informado');
INSERT INTO dim_localidade (sk_localidade, uf_sigla, uf_nome, regiao)
    VALUES (-1, 'NI', 'NÃO INFORMADO', 'Não informado');


-- -------------------------------------------------------------------------------------
-- FATO: o que foi comprado. Uma linha por item de contratacao, ja com o vencedor.
-- -------------------------------------------------------------------------------------
CREATE TABLE fato_item_contratado (
    sk_fato                    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- chave natural do item: o par (contratacao + numero do item) nao pode repetir
    numero_controle_pncp       VARCHAR(50)    NOT NULL,
    numero_item                INTEGER        NOT NULL,

    -- ligacoes com as dimensoes (toda FK precisa apontar pra uma linha que existe)
    sk_orgao                   INTEGER        NOT NULL REFERENCES dim_orgao (sk_orgao),
    sk_fornecedor              INTEGER        NOT NULL REFERENCES dim_fornecedor (sk_fornecedor),
    sk_modalidade              INTEGER        NOT NULL REFERENCES dim_modalidade (sk_modalidade),
    sk_localidade              INTEGER        NOT NULL REFERENCES dim_localidade (sk_localidade),

    -- datas (a de homologacao fica vazia quando veio ANTES da publicacao, regra 7)
    data_publicacao            DATE           NOT NULL,
    data_homologacao           DATE,

    -- o item
    descricao_item             TEXT,
    perfil_gasto               VARCHAR(20)    NOT NULL,

    -- numeros: preco unitario e quantidade com 4 casas, dinheiro com 2 (DECIMAL, nunca float)
    quantidade                 DECIMAL(18,4)  NOT NULL,
    valor_unitario_estimado    DECIMAL(18,4)  NOT NULL,
    valor_total_estimado       DECIMAL(18,2)  NOT NULL,
    valor_unitario_homologado  DECIMAL(18,4)  NOT NULL,
    valor_total_homologado     DECIMAL(18,2)  NOT NULL,

    -- calculados no Python
    comparavel                 SMALLINT       NOT NULL,
    economia_valor             DECIMAL(18,2),
    dias_ciclo                 INTEGER,

    -- REGRAS: o banco e a segunda barreira, se passar algo errado do Python ele barra aqui
    CONSTRAINT uq_fato_item          UNIQUE (numero_controle_pncp, numero_item),
    CONSTRAINT ck_quantidade         CHECK (quantidade > 0),
    CONSTRAINT ck_valores_positivos  CHECK (valor_unitario_estimado >= 0 AND valor_total_estimado >= 0
                                            AND valor_unitario_homologado >= 0 AND valor_total_homologado >= 0),
    CONSTRAINT ck_comparavel         CHECK (comparavel IN (0, 1)),
    CONSTRAINT ck_economia           CHECK (comparavel = 1 OR economia_valor IS NULL),
    CONSTRAINT ck_perfil             CHECK (perfil_gasto IN ('Bens', 'Serviços', 'Obras e engenharia')),
    CONSTRAINT ck_ciclo              CHECK (dias_ciclo IS NULL OR dias_ciclo >= 0),
    CONSTRAINT ck_cronologia         CHECK (data_homologacao IS NULL OR data_homologacao >= data_publicacao)
);

-- indices nas ligacoes com as dimensoes: deixam as consultas das perguntas mais rapidas
CREATE INDEX ix_fato_orgao      ON fato_item_contratado (sk_orgao);
CREATE INDEX ix_fato_fornecedor ON fato_item_contratado (sk_fornecedor);
CREATE INDEX ix_fato_modalidade ON fato_item_contratado (sk_modalidade);
CREATE INDEX ix_fato_localidade ON fato_item_contratado (sk_localidade);
